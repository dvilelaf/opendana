#!/usr/bin/env bash
# C6.42: regenerate every icon derivative from packaging/icon/opendana.svg.
# OpenDana's own branding (an isometric ice cube); not game content. Needs
# rsvg-convert and ImageMagick. Run from anywhere; outputs are committed so the
# package builds from the source archive need neither tool.
#   packaging/icon/png/opendana-<n>.png   n = 16 24 32 48 64 128 256 512
#   packaging/icon/opendana.ico           16..256, PNG entries (make-ico.py)
#   packaging/linux/opendana.png          256 px (AppImage .DirIcon, .desktop)
#   src/render/icon_data.h                   256x256 RGBA for SDL_SetWindowIcon (C6.44:
#                                            the window manager only ever downscales)
set -euo pipefail
here="$(cd "$(dirname "$0")" && pwd)"
root="$(cd "$here/../.." && pwd)"
svg="$here/opendana.svg"
mkdir -p "$here/png"
for n in 16 24 32 48 64 128 256 512; do
    rsvg-convert -w "$n" -h "$n" "$svg" -o "$here/png/opendana-$n.png"
done
python3 "$here/make-ico.py" "$here/opendana.ico" "$here"/png/opendana-{16,24,32,48,64,128,256}.png
# .DirIcon / .desktop icon: the 256 px render taken directly from the SVG
cp -- "$here/png/opendana-256.png" "$root/packaging/linux/opendana.png"
{
    echo '/* Generated by packaging/icon/make-icons.sh from packaging/icon/opendana.svg. */'
    echo '#ifndef OD_ICON_DATA_H'
    echo '#define OD_ICON_DATA_H'
    echo '#define OD_ICON_W 256'
    echo '#define OD_ICON_H 256'
    echo 'static const unsigned char od_icon_rgba[256 * 256 * 4] = {'
    convert "$here/png/opendana-256.png" -depth 8 rgba:- | od -An -v -tu1 -w16 \
        | sed 's/^ *//; s/  */,/g; s/$/,/'
    echo '};'
    echo '#endif'
} > "$root/src/render/icon_data.h"
echo "icons regenerated"

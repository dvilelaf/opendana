static int glyph_pixel(unsigned char c, int row, int col)
{
    if (c >= 128)
        c = '?';
    return (od_font8x8[c][row] >> col) & 1;
}

/* C6.32: one glyph per UTF-8 code point. The font has ASCII only, so any
 * other code point (a typed accent, a path from the system chooser) is drawn
 * as one '?' and counts as one character everywhere (width, fit, wrap). */
static size_t u8_step(const unsigned char *p)
{
    if (p[0] < 0xC0)
        return 1;                       /* ASCII or a stray continuation  */
    size_t n = p[0] >= 0xF0 ? 4 : p[0] >= 0xE0 ? 3 : 2;
    for (size_t i = 1; i < n; i++)
        if ((p[i] & 0xC0) != 0x80)
            return i;                   /* truncated sequence             */
    return n;
}

/* Code points in the first `bytes` bytes of `s`. */
static size_t u8_count(const char *s, size_t bytes)
{
    size_t n = 0;
    for (size_t i = 0; i < bytes && s[i];) {
        i += u8_step((const unsigned char *)s + i);
        n++;
    }
    return n;
}

/* Byte offset of code point `n` in `s` (or its length). */
static size_t u8_offset(const char *s, size_t len, size_t n)
{
    size_t i = 0;
    while (i < len && s[i] && n > 0) {
        i += u8_step((const unsigned char *)s + i);
        n--;
    }
    return i > len ? len : i;
}

int od_ui_font_text(uint32_t *canvas, int cw, int ch, int x, int y,
                     const char *text, uint32_t argb, int scale)
{
    if (canvas == NULL || text == NULL || scale < 1)
        return 0;

    unsigned a = (argb >> 24) & 0xffu;
    unsigned sr = (argb >> 16) & 0xffu, sg = (argb >> 8) & 0xffu, sb = argb & 0xffu;

    int advance = OD_UI_FONT_W * scale;
    int cx = x;
    for (const char *p = text; *p; p += u8_step((const unsigned char *)p)) {
        unsigned char c = (unsigned char)*p;
        for (int row = 0; row < OD_UI_FONT_H; row++) {
            for (int col = 0; col < OD_UI_FONT_W; col++) {
                if (!glyph_pixel(c, row, col))
                    continue;
                for (int sy = 0; sy < scale; sy++) {
                    int py = y + row * scale + sy;
                    if (py < 0 || py >= ch)
                        continue;
                    for (int sx = 0; sx < scale; sx++) {
                        int px = cx + col * scale + sx;
                        if (px < 0 || px >= cw)
                            continue;
                        uint32_t *dst = &canvas[(size_t)py * (size_t)cw + (size_t)px];
                        if (a == 0) {
                            continue;
                        } else if (a == 255) {
                            *dst = argb;
                        } else {
                            unsigned dr = (*dst >> 16) & 0xffu;
                            unsigned dg = (*dst >> 8) & 0xffu;
                            unsigned db = *dst & 0xffu;
                            unsigned r = (sr * a + dr * (255u - a)) / 255u;
                            unsigned g = (sg * a + dg * (255u - a)) / 255u;
                            unsigned b = (sb * a + db * (255u - a)) / 255u;
                            *dst = 0xff000000u | (r << 16) | (g << 8) | b;
                        }
                    }
                }
            }
        }
        cx += advance;
    }
    return cx - x;
}

int od_ui_font_width(const char *text, int scale)
{
    if (text == NULL || scale < 1)
        return 0;
    return (int)u8_count(text, strlen(text)) * OD_UI_FONT_W * scale;
}

/* Copy at most `n` characters (code points) of the `len` bytes at `text` into
 * `out`, ending in "..." when the text is longer than `n`. */
static void fit_chars(const char *text, size_t len, int n, char *out, size_t cap)
{
    if (cap == 0)
        return;
    if (n < 0)
        n = 0;
    size_t chars = u8_count(text, len);
    size_t keep = len;
    const char *dots = "";
    if (chars > (size_t)n) {
        if (n >= 4) {
            keep = u8_offset(text, len, (size_t)n - 3);
            dots = "...";
        } else {
            keep = u8_offset(text, len, (size_t)n);
        }
    }
    if (keep + strlen(dots) + 1 > cap) {   /* never cut inside a sequence */
        size_t room = cap - 1 - strlen(dots);
        size_t k = 0;
        while (k < keep) {
            size_t step = u8_step((const unsigned char *)text + k);
            if (k + step > room)
                break;
            k += step;
        }
        keep = k;
    }
    memcpy(out, text, keep);
    memcpy(out + keep, dots, strlen(dots));
    out[keep + strlen(dots)] = '\0';
}

const char *od_ui_font_fit(const char *text, int max_w, int scale,
                            char *out, size_t cap)
{
    if (out == NULL || cap == 0)
        return "";
    if (text == NULL || scale < 1) {
        out[0] = '\0';
        return out;
    }
    fit_chars(text, strlen(text), max_w / (OD_UI_FONT_W * scale), out, cap);
    return out;
}

int od_ui_font_wrap(const char *text, int max_w, int scale, char *out,
                     size_t line_cap, int max_lines)
{
    if (out == NULL || line_cap == 0 || max_lines < 1 || text == NULL ||
        scale < 1)
        return 0;
    int per_line = max_w / (OD_UI_FONT_W * scale);
    if (per_line < 1)
        return 0;
    int lines = 0;
    const char *p = text;
    while (*p == ' ')
        p++;
    while (*p != '\0' && lines < max_lines) {
        char *line = out + (size_t)lines * line_cap;
        size_t rest = strlen(p);
        if (lines == max_lines - 1 || u8_count(p, rest) <= (size_t)per_line) {
            fit_chars(p, rest, per_line, line, line_cap);
            lines++;
            break;
        }
        /* Break at the last space that keeps the line within per_line. */
        size_t limit = u8_offset(p, rest, (size_t)per_line);
        size_t cut = 0;
        for (size_t i = 0; i <= limit && i < rest; i++)
            if (p[i] == ' ')
                cut = i;
        if (cut == 0)
            cut = limit;                       /* one long word: split it */
        fit_chars(p, cut, per_line, line, line_cap);
        for (size_t l = strlen(line); l > 0 && line[l - 1] == ' '; l--)
            line[l - 1] = '\0';
        lines++;
        p += cut;
        while (*p == ' ')
            p++;
    }
    return lines;
}

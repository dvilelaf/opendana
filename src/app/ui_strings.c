const char *od_str(od_string id)
{
    if (id < 0 || id >= OD_STR_COUNT || table[id] == 0)
        return "";
    return table[id];
}

const char *od_str_bool(int value)
{
    return value ? od_str(OD_STR_ON) : od_str(OD_STR_OFF);
}

#!/usr/bin/env python3
"""Derive a mod's CHR sheet from the imported content package (C6.18).

The example mods (`mods/example`, `content/mods/test-gfx`) change Hero's CHR
tiles: indices 1024..1037 of the 128 KiB CHR, which are the first 14 tiles of
sheet 1 (``graphics/chr/chr-01.png``). A full derived sheet would version the
rest of the original CHR, and the release checks flag exactly that
(see the release policy).

So the repository ships **no** mod CHR. This tool rebuilds the sheet from the
**user's imported package** (``content/base``, produced by ``opendana --import-rom``)
and applies only the Hero transform, writing it into the mod directory:

    python3 tools/content/make_mod_chr.py --base PACK --out DIR --style hatch
    python3 tools/content/make_mod_chr.py --base PACK --out DIR --style solid

The mod then overlays the generated file by relative path, exactly as before.
The generated bytes are derived from the ROM of the user, never committed.

    python3 tools/content/make_mod_chr.py --self-test

The self-test builds a synthetic sheet (no ROM) and checks that the transform
touches Hero's tiles only and that the output is a valid indexed sheet.
"""
from __future__ import annotations

import argparse
import json
import struct
import sys
import zlib
from pathlib import Path

# Hero's two sprite layers in the world-1 bank: indices 1024..1037 (CHR sheet 1).
HERO_TILES = [0x400, 0x401, 0x402, 0x403, 0x404, 0x405, 0x406, 0x407,
              0x408, 0x409, 0x40C, 0x40D]
TILE_BYTES = 16
TILES_PER_ROW = 32
TILES_PER_SHEET = 1024
SHEET_REL = "graphics/chr/chr-01.png"
GREY = [(0, 0, 0), (85, 85, 85), (170, 170, 170), (255, 255, 255)]


# --------------------------------------------------------------------------
# Minimal 8-bit indexed PNG reader / writer (same convention as export_gfx).
# --------------------------------------------------------------------------

def _paeth(a: int, b: int, c: int) -> int:
    p = a + b - c
    pa, pb, pc = abs(p - a), abs(p - b), abs(p - c)
    if pa <= pb and pa <= pc:
        return a
    if pb <= pc:
        return b
    return c


def _grey_to_2bpp(v: int) -> int:
    return {0: 0, 85: 1, 170: 2, 255: 3}[v]


def read_chr_png(data: bytes):
    """(width, height, values 0..3) of a CHR sheet.

    Accepts the two encodings the package uses: 8-bit greyscale (levels
    0/85/170/255, what `opendana --import-rom` writes) and 8-bit indexed with a
    four-grey palette (what `tools/content/export_gfx.py` writes). Both decode
    to the same 2-bit tiles the loader expects.
    """
    assert data[:8] == b"\x89PNG\r\n\x1a\n", "not a PNG"
    pos = 8
    width = height = depth = ctype = None
    palette = []
    idat = bytearray()
    while pos < len(data):
        length = struct.unpack(">I", data[pos:pos + 4])[0]
        tag = data[pos + 4:pos + 8]
        body = data[pos + 8:pos + 8 + length]
        pos += 12 + length
        if tag == b"IHDR":
            width, height, depth, ctype = struct.unpack(">IIBB", body[:10])
        elif tag == b"PLTE":
            palette = [tuple(body[i:i + 3]) for i in range(0, len(body), 3)]
        elif tag == b"IDAT":
            idat += body
        elif tag == b"IEND":
            break
    assert depth == 8 and ctype in (0, 3), "expected an 8-bit grey/indexed PNG"
    raw = zlib.decompress(bytes(idat))
    stride = width
    assert len(raw) == height * (stride + 1), "unexpected raw size"
    out = bytearray()
    prev = bytearray(stride)
    p = 0
    for _y in range(height):
        f = raw[p]
        p += 1
        line = bytearray(raw[p:p + stride])
        p += stride
        if f == 1:
            for i in range(1, stride):
                line[i] = (line[i] + line[i - 1]) & 0xFF
        elif f == 2:
            for i in range(stride):
                line[i] = (line[i] + prev[i]) & 0xFF
        elif f == 3:
            for i in range(stride):
                a = line[i - 1] if i else 0
                line[i] = (line[i] + ((a + prev[i]) >> 1)) & 0xFF
        elif f == 4:
            for i in range(stride):
                a = line[i - 1] if i else 0
                c = prev[i - 1] if i else 0
                line[i] = (line[i] + _paeth(a, prev[i], c)) & 0xFF
        elif f != 0:
            raise AssertionError(f"unknown PNG filter {f}")
        if ctype == 0:
            out += bytes(_grey_to_2bpp(v) for v in line)
        else:
            for v in line:
                r, g, b = palette[v]
                out.append(_grey_to_2bpp((r * 77 + g * 150 + b * 29) >> 8))
        prev = line
    return width, height, out


def png_indexed(width: int, height: int, indices: bytes,
                palette) -> bytes:
    assert len(indices) == width * height

    def chunk(tag: bytes, data: bytes) -> bytes:
        return (struct.pack(">I", len(data)) + tag + data +
                struct.pack(">I", zlib.crc32(tag + data) & 0xFFFFFFFF))

    ihdr = struct.pack(">IIBBBBB", width, height, 8, 3, 0, 0, 0)
    plte = b"".join(bytes(c) for c in palette)
    raw = bytearray()
    for y in range(height):
        raw.append(0)
        raw += indices[y * width:(y + 1) * width]
    return (b"\x89PNG\r\n\x1a\n" + chunk(b"IHDR", ihdr) + chunk(b"PLTE", plte) +
            chunk(b"IDAT", zlib.compress(bytes(raw), 9)) + chunk(b"IEND", b""))


# --------------------------------------------------------------------------
# Locate the sheet that holds Hero's global tiles, and transform it.
# --------------------------------------------------------------------------

def sheet_for_tile(pack: Path, tile: int) -> str:
    """Relative path of the CHR sheet holding global `tile`, per pack.json."""
    pack_doc = json.loads((pack / "pack.json").read_text(encoding="utf-8"))
    chr_files = pack_doc.get("graphics", {}).get("chr")
    if not isinstance(chr_files, list) or not chr_files:
        raise SystemExit("pack.json has no graphics.chr list")
    done = 0
    for rel in chr_files:
        w, h, _values = read_chr_png((pack / rel).read_bytes())
        tiles = (w // 8) * (h // 8)
        if tile < done + tiles:
            return rel
        done += tiles
    raise SystemExit(f"no CHR sheet holds tile {tile:#x}")


def transform(indices: bytearray, width: int, tiles: list[int],
              style: str) -> None:
    """Rewrite Hero's tiles in place. `tiles` are sheet-local tile indices."""
    row = width // 8
    for t in tiles:
        tx = (t % row) * 8
        ty = (t // row) * 8
        for y in range(8):
            for x in range(8):
                off = (ty + y) * width + tx + x
                v = indices[off]
                if not v:
                    continue
                if style == "hatch":
                    # Keep transparency, hatch the silhouette.
                    indices[off] = 3 if (x + y) % 2 == 0 else 1
                elif style == "solid":
                    indices[off] = 3
                else:
                    raise SystemExit(f"unknown style {style!r}")


def build_chr_sheet(base: Path, out: Path, style: str) -> Path:
    """Rebuild sheet 1 from `base` with Hero transformed into `out`."""
    rel = sheet_for_tile(base, HERO_TILES[0])
    w, h, idx = read_chr_png((base / rel).read_bytes())
    assert w == h and w % 8 == 0, "unexpected CHR sheet size"
    local = [t % TILES_PER_SHEET for t in HERO_TILES]
    buf = bytearray(idx)
    transform(buf, w, local, style)
    dest = out / rel
    dest.parent.mkdir(parents=True, exist_ok=True)
    dest.write_bytes(png_indexed(w, h, bytes(buf), GREY))
    return dest


# --------------------------------------------------------------------------
# Self-test: synthetic sheet, no ROM.
# --------------------------------------------------------------------------

def self_test() -> int:
    import tempfile

    rng = 0x6C68

    def next_byte() -> int:
        nonlocal rng
        rng = (rng * 1103515245 + 12345) & 0x7FFFFFFF
        return (rng >> 8) & 0xFF

    ok = True
    with tempfile.TemporaryDirectory() as tmp:
        base = Path(tmp) / "pack"
        (base / "graphics" / "chr").mkdir(parents=True)
        # Two synthetic sheets; sheet 0 has no Hero, sheet 1 does.
        for f in range(2):
            idx = bytearray(TILES_PER_ROW * 8 * TILES_PER_ROW * 8)
            for i in range(len(idx)):
                idx[i] = next_byte() & 3
            (base / "graphics" / "chr" / f"chr-{f:02d}.png").write_bytes(
                png_indexed(TILES_PER_ROW * 8, TILES_PER_ROW * 8, bytes(idx), GREY))
        (base / "pack.json").write_text(json.dumps({
            "schema_version": 2, "id": "synthetic",
            "graphics": {"chr": ["graphics/chr/chr-00.png",
                                 "graphics/chr/chr-01.png"]}}), encoding="utf-8")

        before = read_chr_png((base / "graphics/chr/chr-01.png").read_bytes())[2]
        for style in ("hatch", "solid"):
            out = Path(tmp) / f"mod-{style}"
            dest = build_chr_sheet(base, out, style)
            w, h, after = read_chr_png(dest.read_bytes())
            assert (w, h) == (256, 256)
            changed = set()
            row = w // 8
            for t in range(TILES_PER_SHEET):
                tx = (t % row) * 8
                ty = (t // row) * 8
                diff = False
                for y in range(8):
                    for x in range(8):
                        if before[(ty + y) * w + tx + x] != after[(ty + y) * w + tx + x]:
                            diff = True
                if diff:
                    changed.add(t)
            good = changed and changed <= set(range(14))
            print(f"  [{'ok' if good else 'FALLO'}] style={style}: "
                  f"{len(changed)} tiles changed, all in $400..$40D")
            ok = ok and good
    return 0 if ok else 1


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--base", type=Path, help="imported package (pack.json)")
    ap.add_argument("--out", type=Path, help="mod directory to write into")
    ap.add_argument("--style", choices=("hatch", "solid"), default="hatch")
    ap.add_argument("--self-test", action="store_true")
    args = ap.parse_args()

    if args.self_test:
        print("== self-test de make_mod_chr ==")
        rc = self_test()
        print("self-test:", "OK" if rc == 0 else "FALLO")
        return rc
    if args.base is None or args.out is None:
        ap.error("--base and --out are required (or use --self-test)")
    if not (args.base / "pack.json").is_file():
        print(f"BLOCKED: no package at '{args.base}'", file=sys.stderr)
        return 2
    dest = build_chr_sheet(args.base, args.out, args.style)
    print(f"wrote {dest} (style={args.style}, Hero tiles $400..$40D)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
